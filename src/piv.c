/*
 * PIV applet.
 *
 * Supported: SELECT, GET DATA, PUT DATA, VERIFY, CHANGE REFERENCE DATA,
 * RESET RETRY COUNTER, GENERAL AUTHENTICATE (ECDSA and ECDH with P-384 keys
 * in slots 9A/9C/9D/9E, 3DES management key 9B), GET RESPONSE and command
 * chaining, plus the Yubico extensions that yubico-piv-tool needs to load
 * keys: IMPORT KEY, SET MANAGEMENT KEY, GET VERSION, GET SERIAL and RESET.
 * There is no on-card key generation: keys come from the host.
 *
 * A locked build (FORE_LOCKED) has exactly one key: the one compiled in from
 * preload.h, with its certificate. Both are served from the firmware image,
 * so no command can replace or delete them, and keys or certificates left in
 * storage by another build are ignored.
 */
#include "piv.h"

#include <string.h>

#include "des.h"
#include "p384.h"
#include "platform.h"
#include "sha512.h"
#include "store.h"

#ifdef FORE_LOCKED
#include "preload.h" /* generated by tools/gen-preload.py */
#define LOCKED 1
#else
#define LOCKED 0
#endif

#define ALG_3DES 0x03
#define ALG_ECCP384 0x14

#define POLICY_DEFAULT 0
#define POLICY_NEVER 1
#define POLICY_ONCE 2
#define POLICY_ALWAYS 3

#define SW_OK 0x9000
#define SW_MEMORY 0x6581
#define SW_WRONG_LENGTH 0x6700
#define SW_SECURITY 0x6982
#define SW_BLOCKED 0x6983
#define SW_CONDITIONS 0x6985
#define SW_WRONG_DATA 0x6a80
#define SW_UNSUPPORTED 0x6a81
#define SW_NOT_FOUND 0x6a82
#define SW_NO_SPACE 0x6a84
#define SW_WRONG_P1P2 0x6a86
#define SW_REF_NOT_FOUND 0x6a88
#define SW_INS 0x6d00
#define SW_CLA 0x6e00
#define SW_TRIES(n) (0x63c0 | (n))

/* Room for the largest object (2 flash pages) plus the PUT DATA header. */
#define CMD_MAX (2 * FLASH_PAGE_SIZE + 16)

const uint8_t piv_atr[] = {
    0x3b, 0x8a, 0x01, 0x80, 0x58, 'f', 'o', 'r', 'e', '-', 'P', 'I', 'V',
    0x8a ^ 0x01 ^ 0x80 ^ 0x58 ^ 'f' ^ 'o' ^ 'r' ^ 'e' ^ '-' ^ 'P' ^ 'I' ^ 'V', /* TCK */
};
const size_t piv_atr_len = sizeof(piv_atr);

static const uint8_t PIV_AID[] ={0xa0, 0x00, 0x00, 0x03, 0x08, 0x00, 0x00, 0x10, 0x00, 0x01, 0x00};
static const uint8_t SLOTS[NUM_KEYS] = {0x9a, 0x9c, 0x9d, 0x9e};
static const uint32_t CERT_TAGS[NUM_KEYS] = {0x5fc105, 0x5fc10a, 0x5fc10b, 0x5fc101};
static const uint8_t SLOT_POLICY[NUM_KEYS] = {POLICY_ONCE, POLICY_ALWAYS, POLICY_ONCE, POLICY_NEVER};

static const uint8_t SELECT_RESPONSE[] = {
    0x61, 0x26,
    0x4f, 0x06, 0x00, 0x00, 0x10, 0x00, 0x01, 0x00,
    0x79, 0x07, 0x4f, 0x05, 0xa0, 0x00, 0x00, 0x03, 0x08,
    0x50, 0x08, 'f', 'o', 'r', 'e', ' ', 'P', 'I', 'V',
    0xac, 0x09, 0x80, 0x01, ALG_3DES, 0x80, 0x01, ALG_ECCP384, 0x06, 0x01, 0x00,
};

static const uint8_t DISCOVERY[] = {
    0x7e, 0x12,
    0x4f, 0x0b, 0xa0, 0x00, 0x00, 0x03, 0x08, 0x00, 0x00, 0x10, 0x00, 0x01, 0x00,
    0x5f, 0x2f, 0x02, 0x40, 0x00, /* PIV PIN only */
};

/* yubico-piv-tool's CHUID template; the GUID is filled in per device. */
static const uint8_t CHUID_HEAD[] = {
    0x53, 0x3b,
    0x30, 0x19, 0xd4, 0xe7, 0x39, 0xda, 0x73, 0x9c, 0xed, 0x39, 0xce, 0x73, 0x9d,
    0x83, 0x68, 0x58, 0x21, 0x08, 0x42, 0x10, 0x84, 0x21, 0xc8, 0x42, 0x10, 0xc3, 0xeb,
    0x34, 0x10,
};
static const uint8_t CHUID_TAIL[] = {
    0x35, 0x08, '2', '0', '9', '9', '1', '2', '3', '1', 0x3e, 0x00, 0xfe, 0x00,
};

static struct {
    uint8_t pin_verified;
    uint8_t pin_fresh; /* PIN verified and not yet spent on a PIN-always key */
    uint8_t mgmt_auth;
    uint8_t witness_valid;
    uint8_t challenge_valid;
    uint8_t witness[8];
    uint8_t challenge[8];
} sess;

static uint8_t cmd_buf[CMD_MAX];
static size_t cmd_len;
static uint8_t chain_hdr[3]; /* INS P1 P2 of the chain in progress */
static uint8_t chaining;

static uint8_t out[300];
static const uint8_t *pending;
static size_t pending_len;

typedef struct {
    uint16_t sw;
    const uint8_t *data;
    size_t len;
} reply;

static reply status(uint16_t sw)
{
    reply r = {sw, NULL, 0};
    return r;
}

static reply data_reply(const uint8_t *data, size_t len)
{
    reply r = {SW_OK, data, len};
    return r;
}

static int ct_equal(const uint8_t *a, const uint8_t *b, size_t n)
{
    uint8_t d = 0;
    for (size_t i = 0; i < n; i++)
        d |= a[i] ^ b[i];
    return d == 0;
}

static void wipe(void *p, size_t n)
{
    volatile uint8_t *v = p;
    while (n--)
        *v++ = 0;
}

uint32_t piv_serial(void)
{
    uint8_t h[64];
    sha512_ctx c;

    sha512_init(&c);
    sha512_update(&c, "fore-serial", 11);
    sha512_update(&c, device_uid(), 12);
    sha512_final(&c, h, sizeof(h));
    return ((uint32_t)h[0] << 24 | (uint32_t)h[1] << 16 | (uint32_t)h[2] << 8 | h[3]) & 0x7fffffff;
}

static int is_cert_tag(uint32_t tag)
{
    for (int i = 0; i < NUM_KEYS; i++)
        if (CERT_TAGS[i] == tag)
            return 1;
    return 0;
}

static int slot_index(uint8_t slot)
{
    for (int i = 0; i < NUM_KEYS; i++)
        if (SLOTS[i] == slot)
            return i;
    return -1;
}

/* Reads a BER-TLV length. Returns 0 on success. */
static int read_len(const uint8_t **p, const uint8_t *end, size_t *len)
{
    const uint8_t *q = *p;

    if (q >= end)
        return -1;
    if (*q < 0x80) {
        *len = *q++;
    } else if (*q == 0x81 && end - q >= 2) {
        *len = q[1];
        q += 2;
    } else if (*q == 0x82 && end - q >= 3) {
        *len = (size_t)q[1] << 8 | q[2];
        q += 3;
    } else {
        return -1;
    }
    if ((size_t)(end - q) < *len)
        return -1;
    *p = q;
    return 0;
}

/* Remaining tries for a PIN/PUK reference. */
static int tries_left(int ref)
{
    int left = g_state.max_tries[ref] - store_failures(ref);
    return left > 0 ? left : 0;
}

/*
 * Checks an 8-byte PIN/PUK block against the stored value. The failure is
 * recorded before comparing so pulling power mid-check cannot save a try.
 */
static uint16_t check_ref(int ref, const uint8_t *given)
{
    const uint8_t *want = ref == PIN_REF ? g_state.pin : g_state.puk;
    int failures = store_failures(ref);

    if (tries_left(ref) == 0)
        return SW_BLOCKED;
    store_add_failure(ref);
    if (store_failures(ref) != failures + 1)
        return SW_MEMORY;
    if (!ct_equal(given, want, 8))
        return SW_TRIES(tries_left(ref));
    store_clear_failures(ref);
    return SW_OK;
}

/* 6 to 8 bytes, padded with 0xFF. */
static int valid_ref_value(const uint8_t *v)
{
    int n = 8;
    while (n > 0 && v[n - 1] == 0xff)
        n--;
    for (int i = 0; i < n; i++)
        if (v[i] == 0xff)
            return 0;
    return n >= 6;
}

static reply cmd_select(uint8_t p1, const uint8_t *data, size_t lc)
{
    if (p1 != 0x04 || lc < 5 || lc > sizeof(PIV_AID) || memcmp(data, PIV_AID, lc) != 0)
        return status(SW_NOT_FOUND);
    return data_reply(SELECT_RESPONSE, sizeof(SELECT_RESPONSE));
}

static reply cmd_get_data(uint8_t p1, uint8_t p2, const uint8_t *data, size_t lc)
{
    uint32_t tag = 0;
    const uint8_t *obj;
    size_t len;
    int idx;

    if (p1 != 0x3f || p2 != 0xff)
        return status(SW_WRONG_P1P2);
    if (lc < 3 || data[0] != 0x5c || data[1] < 1 || data[1] > 3 || lc != 2u + data[1])
        return status(SW_WRONG_DATA);
    for (unsigned i = 0; i < data[1]; i++)
        tag = tag << 8 | data[2 + i];

    if (tag == 0x7e)
        return data_reply(DISCOVERY, sizeof(DISCOVERY));
#ifdef FORE_LOCKED
    if (is_cert_tag(tag))
        return tag == PRELOAD_CERT_TAG ? data_reply(preload_cert, sizeof(preload_cert)) : status(SW_NOT_FOUND);
#endif
    idx = store_object_index(tag);
    if (idx < 0)
        return status(SW_NOT_FOUND);
    obj = store_object(idx, &len);
    if (obj)
        return data_reply(obj, len);
    if (tag == 0x5fc102) {
        uint8_t h[64];
        sha512_ctx c;
        sha512_init(&c);
        sha512_update(&c, "fore-guid", 9);
        sha512_update(&c, device_uid(), 12);
        sha512_final(&c, h, sizeof(h));
        memcpy(out, CHUID_HEAD, sizeof(CHUID_HEAD));
        memcpy(out + sizeof(CHUID_HEAD), h, 16);
        memcpy(out + sizeof(CHUID_HEAD) + 16, CHUID_TAIL, sizeof(CHUID_TAIL));
        return data_reply(out, sizeof(CHUID_HEAD) + 16 + sizeof(CHUID_TAIL));
    }
    return status(SW_NOT_FOUND);
}

static reply cmd_put_data(uint8_t p1, uint8_t p2, const uint8_t *data, size_t lc)
{
    const uint8_t *end = data + lc, *p, *body;
    uint32_t tag = 0;
    size_t len;
    int idx;

    if (!sess.mgmt_auth)
        return status(SW_SECURITY);
    if (p1 != 0x3f || p2 != 0xff)
        return status(SW_WRONG_P1P2);
    if (lc < 3 || data[0] != 0x5c || data[1] < 1 || data[1] > 3 || lc < 2u + data[1])
        return status(SW_WRONG_DATA);
    for (unsigned i = 0; i < data[1]; i++)
        tag = tag << 8 | data[2 + i];
    if (LOCKED && is_cert_tag(tag))
        return status(SW_UNSUPPORTED);

    /* The rest must be exactly one 53 TLV, stored and returned verbatim. */
    body = p = data + 2 + data[1];
    if (p >= end || *p++ != 0x53 || read_len(&p, end, &len) || p + len != end)
        return status(SW_WRONG_DATA);
    idx = store_object_index(tag);
    if (idx < 0)
        return status(SW_NO_SPACE);
    if (store_put_object(idx, body, len ? (size_t)(end - body) : 0))
        return status(SW_NO_SPACE);
    return status(SW_OK);
}

static reply cmd_verify(uint8_t p1, uint8_t p2, const uint8_t *data, size_t lc)
{
    uint16_t sw;

    if (p2 != 0x80)
        return status(SW_REF_NOT_FOUND);
    if (p1 == 0xff) {
        if (lc != 0)
            return status(SW_WRONG_DATA);
        sess.pin_verified = sess.pin_fresh = 0;
        return status(SW_OK);
    }
    if (p1 != 0x00)
        return status(SW_WRONG_P1P2);
    if (lc == 0) {
        if (tries_left(PIN_REF) == 0)
            return status(SW_BLOCKED);
        return status(sess.pin_verified ? SW_OK : SW_TRIES(tries_left(PIN_REF)));
    }
    if (lc != 8)
        return status(SW_WRONG_DATA);
    sw = check_ref(PIN_REF, data);
    sess.pin_verified = sess.pin_fresh = sw == SW_OK;
    return status(sw);
}

static reply cmd_change_reference(uint8_t p1, uint8_t p2, const uint8_t *data, size_t lc)
{
    int ref = p2 == 0x80 ? PIN_REF : p2 == 0x81 ? PUK_REF : -1;
    uint16_t sw;

    if (ref < 0)
        return status(SW_REF_NOT_FOUND);
    if (p1 != 0x00)
        return status(SW_WRONG_P1P2);
    if (lc != 16)
        return status(SW_WRONG_DATA);
    sw = check_ref(ref, data);
    if (sw != SW_OK)
        return status(sw);
    if (!valid_ref_value(data + 8))
        return status(SW_WRONG_DATA);
    memcpy(ref == PIN_REF ? g_state.pin : g_state.puk, data + 8, 8);
    if (store_save())
        return status(SW_NO_SPACE);
    if (ref == PIN_REF)
        sess.pin_verified = sess.pin_fresh = 1;
    return status(SW_OK);
}

static reply cmd_reset_retry(uint8_t p1, uint8_t p2, const uint8_t *data, size_t lc)
{
    uint16_t sw;

    if (p2 != 0x80)
        return status(SW_REF_NOT_FOUND);
    if (p1 != 0x00)
        return status(SW_WRONG_P1P2);
    if (lc != 16)
        return status(SW_WRONG_DATA);
    sw = check_ref(PUK_REF, data);
    if (sw != SW_OK)
        return status(sw);
    if (!valid_ref_value(data + 8))
        return status(SW_WRONG_DATA);
    memcpy(g_state.pin, data + 8, 8);
    if (store_save())
        return status(SW_NO_SPACE);
    store_clear_failures(PIN_REF);
    return status(SW_OK);
}

typedef struct {
    const uint8_t *v;
    size_t len;
    int present;
} tlv;

/* Splits a 7C dynamic authentication template into tags 80, 81, 82, 85. */
static int parse_auth_template(const uint8_t *data, size_t lc, tlv t[4])
{
    static const uint8_t tags[4] = {0x80, 0x81, 0x82, 0x85};
    const uint8_t *p = data, *end = data + lc;
    size_t len;

    memset(t, 0, 4 * sizeof(tlv));
    if (lc < 2 || *p++ != 0x7c || read_len(&p, end, &len) || p + len != end)
        return -1;
    while (p < end) {
        uint8_t tag = *p++;
        int i;
        if (read_len(&p, end, &len))
            return -1;
        for (i = 0; i < 4 && tags[i] != tag; i++)
            ;
        if (i == 4 || t[i].present)
            return -1;
        t[i].v = p;
        t[i].len = len;
        t[i].present = 1;
        p += len;
    }
    return 0;
}

/* 7C L tag L value */
static reply auth_reply(uint8_t tag, const uint8_t *v, size_t len)
{
    out[0] = 0x7c;
    out[1] = (uint8_t)(len + 2);
    out[2] = tag;
    out[3] = (uint8_t)len;
    memcpy(out + 4, v, len);
    return data_reply(out, len + 4);
}

/* Management key: SP 800-73-4 mutual (witness) or external (challenge) auth. */
static reply auth_mgmt(uint8_t p1, const tlv *t)
{
    const tlv *witness = &t[0], *challenge = &t[1], *response = &t[2];
    uint8_t buf[8];

    if (p1 != ALG_3DES && p1 != 0x00)
        return status(SW_WRONG_P1P2);

    if (witness->present && witness->len == 0 && !challenge->present && !response->present) {
        sess.mgmt_auth = sess.witness_valid = sess.challenge_valid = 0;
        rng_fill(sess.witness, 8);
        sess.witness_valid = 1;
        des3_encrypt(buf, sess.witness, g_state.mgmt);
        return auth_reply(0x80, buf, 8);
    }
    if (witness->present && witness->len == 8 && !response->present) {
        int ok = sess.witness_valid && ct_equal(witness->v, sess.witness, 8);
        sess.witness_valid = 0;
        if (!ok)
            return status(SW_SECURITY);
        sess.mgmt_auth = 1;
        if (!challenge->present)
            return status(SW_OK);
        if (challenge->len != 8)
            return status(SW_WRONG_DATA);
        des3_encrypt(buf, challenge->v, g_state.mgmt);
        return auth_reply(0x82, buf, 8);
    }
    if (challenge->present && challenge->len == 0 && !witness->present && !response->present) {
        sess.mgmt_auth = sess.witness_valid = sess.challenge_valid = 0;
        rng_fill(sess.challenge, 8);
        sess.challenge_valid = 1;
        return auth_reply(0x81, sess.challenge, 8);
    }
    if (response->present && response->len == 8 && !witness->present && !challenge->present) {
        int ok;
        des3_encrypt(buf, sess.challenge, g_state.mgmt);
        ok = sess.challenge_valid && ct_equal(response->v, buf, 8);
        sess.challenge_valid = 0;
        if (!ok)
            return status(SW_SECURITY);
        sess.mgmt_auth = 1;
        return status(SW_OK);
    }
    return status(SW_WRONG_DATA);
}

static size_t der_int(uint8_t *o, const uint8_t *v, size_t n)
{
    size_t pad;

    while (n > 1 && *v == 0) {
        v++;
        n--;
    }
    pad = *v >> 7;
    o[0] = 0x02;
    o[1] = (uint8_t)(n + pad);
    o[2] = 0;
    memcpy(o + 2 + pad, v, n);
    return 2 + pad + n;
}

/* The private scalar for slot index k, or NULL if the slot is empty. */
static const uint8_t *slot_key(int k, uint8_t *pin_policy)
{
#ifdef FORE_LOCKED
    *pin_policy = POLICY_DEFAULT;
    return k == PRELOAD_KEY_INDEX ? preload_key : NULL;
#else
    *pin_policy = g_state.keys[k].pin_policy;
    return g_state.keys[k].present ? g_state.keys[k].priv : NULL;
#endif
}

static reply auth_key(uint8_t p1, int k, const tlv *t)
{
    const tlv *challenge = &t[1], *response = &t[2], *exponentiation = &t[3];
    uint8_t policy;
    const uint8_t *priv = slot_key(k, &policy);

    if (p1 != ALG_ECCP384)
        return status(SW_WRONG_P1P2);
    if (!priv)
        return status(SW_REF_NOT_FOUND);
    if (!response->present || response->len != 0 || t[0].present ||
        challenge->present == exponentiation->present)
        return status(SW_WRONG_DATA);

    if (policy == POLICY_DEFAULT)
        policy = SLOT_POLICY[k];
    if ((policy == POLICY_ONCE && !sess.pin_verified) ||
        (policy == POLICY_ALWAYS && !sess.pin_fresh))
        return status(SW_SECURITY);
    if (policy == POLICY_ALWAYS)
        sess.pin_fresh = 0;

    if (challenge->present) {
        uint8_t sig[2 * P384_LEN];
        size_t n;
        if (challenge->len == 0 || challenge->len > 64)
            return status(SW_WRONG_DATA);
        if (p384_sign(sig, priv, challenge->v, challenge->len))
            return status(SW_WRONG_DATA);
        /* 7C L 82 L 30 L INTEGER r INTEGER s */
        n = der_int(out + 6, sig, P384_LEN);
        n += der_int(out + 6 + n, sig + P384_LEN, P384_LEN);
        out[0] = 0x7c;
        out[1] = (uint8_t)(n + 4);
        out[2] = 0x82;
        out[3] = (uint8_t)(n + 2);
        out[4] = 0x30;
        out[5] = (uint8_t)n;
        return data_reply(out, n + 6);
    } else {
        uint8_t secret[P384_LEN];
        reply r;
        if (exponentiation->len != 1 + 2 * P384_LEN ||
            p384_ecdh(secret, priv, exponentiation->v))
            return status(SW_WRONG_DATA);
        r = auth_reply(0x82, secret, P384_LEN);
        wipe(secret, sizeof(secret));
        return r;
    }
}

static reply cmd_general_authenticate(uint8_t p1, uint8_t p2, const uint8_t *data, size_t lc)
{
    tlv t[4];
    int k;

    if (parse_auth_template(data, lc, t))
        return status(SW_WRONG_DATA);
    if (p2 == 0x9b)
        return auth_mgmt(p1, t);
    k = slot_index(p2);
    if (k < 0)
        return status(SW_REF_NOT_FOUND);
    return auth_key(p1, k, t);
}

/* Yubico: 06 30 <scalar> [AA 01 pin-policy] [AB 01 touch-policy] */
static reply cmd_import_key(uint8_t p1, uint8_t p2, const uint8_t *data, size_t lc)
{
    const uint8_t *p = data, *end = data + lc, *scalar = NULL;
    uint8_t pin_policy = POLICY_DEFAULT;
    int k = slot_index(p2);

    if (!sess.mgmt_auth)
        return status(SW_SECURITY);
    if (k < 0)
        return status(SW_WRONG_P1P2);
    if (p1 != ALG_ECCP384)
        return status(SW_WRONG_DATA);
    while (p < end) {
        uint8_t tag = *p++;
        size_t len;
        if (read_len(&p, end, &len))
            return status(SW_WRONG_DATA);
        if (tag == 0x06 && len == P384_LEN)
            scalar = p;
        else if (tag == 0xaa && len == 1 && p[0] <= POLICY_ALWAYS)
            pin_policy = p[0];
        else if (tag == 0xab && len == 1 && p[0] <= 1)
            ; /* touch policy: there is no button, so only "default"/"never" */
        else
            return status(SW_WRONG_DATA);
        p += len;
    }
    if (!scalar || p384_check_scalar(scalar))
        return status(SW_WRONG_DATA);

    g_state.keys[k].present = 1;
    g_state.keys[k].pin_policy = pin_policy;
    memcpy(g_state.keys[k].priv, scalar, P384_LEN);
    if (store_save())
        return status(SW_NO_SPACE);
    return status(SW_OK);
}

/* Yubico: 03 9B 18 <24-byte 3DES key> */
static reply cmd_set_mgmt(uint8_t p1, uint8_t p2, const uint8_t *data, size_t lc)
{
    if (!sess.mgmt_auth)
        return status(SW_SECURITY);
    if (p1 != 0xff || (p2 != 0xff && p2 != 0xfe))
        return status(SW_WRONG_P1P2);
    if (lc != 27 || data[0] != ALG_3DES || data[1] != 0x9b || data[2] != 24)
        return status(SW_WRONG_DATA);
    memcpy(g_state.mgmt, data + 3, 24);
    if (store_save())
        return status(SW_NO_SPACE);
    return status(SW_OK);
}

/* Yubico: wipes the applet, but only once both PIN and PUK are blocked. */
static reply cmd_reset(void)
{
    if (tries_left(PIN_REF) || tries_left(PUK_REF))
        return status(SW_CONDITIONS);
    store_format();
    piv_reset();
    return status(SW_OK);
}

static reply dispatch(uint8_t ins, uint8_t p1, uint8_t p2, const uint8_t *data, size_t lc)
{
    switch (ins) {
    case 0xa4:
        return cmd_select(p1, data, lc);
    case 0xcb:
        return cmd_get_data(p1, p2, data, lc);
    case 0xdb:
        return cmd_put_data(p1, p2, data, lc);
    case 0x20:
        return cmd_verify(p1, p2, data, lc);
    case 0x24:
        return cmd_change_reference(p1, p2, data, lc);
    case 0x2c:
        return cmd_reset_retry(p1, p2, data, lc);
    case 0x87:
        return cmd_general_authenticate(p1, p2, data, lc);
    case 0xfe:
        return LOCKED ? status(SW_UNSUPPORTED) : cmd_import_key(p1, p2, data, lc);
    case 0xff:
        return cmd_set_mgmt(p1, p2, data, lc);
    case 0xfb:
        return cmd_reset();
    case 0xfd:
        out[0] = PIV_VERSION_MAJOR;
        out[1] = PIV_VERSION_MINOR;
        out[2] = PIV_VERSION_PATCH;
        return data_reply(out, 3);
    case 0xf8: {
        uint32_t s = piv_serial();
        out[0] = (uint8_t)(s >> 24);
        out[1] = (uint8_t)(s >> 16);
        out[2] = (uint8_t)(s >> 8);
        out[3] = (uint8_t)s;
        return data_reply(out, 4);
    }
    default:
        return status(SW_INS);
    }
}

/* Sends up to le bytes of data and leaves the rest for GET RESPONSE. */
static size_t respond(uint8_t *resp, const uint8_t *data, size_t len, size_t le, uint16_t sw)
{
    pending_len = 0;
    if (len > le) {
        pending = data + le;
        pending_len = len - le;
        len = le;
        sw = 0x6100 | (pending_len > 0xff ? 0 : (uint16_t)pending_len);
    }
    if (len)
        memcpy(resp, data, len);
    resp[len] = (uint8_t)(sw >> 8);
    resp[len + 1] = (uint8_t)sw;
    return len + 2;
}

size_t piv_apdu(const uint8_t *apdu, size_t len, uint8_t *resp)
{
    uint8_t cla, ins, p1, p2;
    const uint8_t *data = apdu + 5;
    size_t lc = 0, le = 256;
    reply r;

    if (len < 4)
        return respond(resp, NULL, 0, 0, SW_WRONG_LENGTH);
    cla = apdu[0];
    ins = apdu[1];
    p1 = apdu[2];
    p2 = apdu[3];
    if (len == 5) {
        le = apdu[4] ? apdu[4] : 256;
    } else if (len > 5) {
        lc = apdu[4];
        if (lc == 0 || (len != 5 + lc && len != 6 + lc)) /* extended APDUs are not supported */
            return respond(resp, NULL, 0, 0, SW_WRONG_LENGTH);
        if (len == 6 + lc && apdu[5 + lc])
            le = apdu[5 + lc];
    }

    if (ins == 0xc0 && cla == 0x00) {
        const uint8_t *p = pending;
        size_t n = pending_len;
        if (!n)
            return respond(resp, NULL, 0, 0, SW_CONDITIONS);
        return respond(resp, p, n, le, SW_OK);
    }
    pending_len = 0;

    if ((cla & ~0x10) != 0x00)
        return respond(resp, NULL, 0, 0, SW_CLA);

    /* Command chaining: buffer the pieces, run the command on the last one. */
    if (chaining && memcmp(chain_hdr, apdu + 1, 3) != 0)
        chaining = 0;
    if (cla & 0x10 || chaining) {
        if (!chaining)
            cmd_len = 0;
        if (cmd_len + lc > sizeof(cmd_buf)) {
            chaining = 0;
            return respond(resp, NULL, 0, 0, SW_WRONG_LENGTH);
        }
        memcpy(cmd_buf + cmd_len, data, lc);
        cmd_len += lc;
        if (cla & 0x10) {
            chaining = 1;
            memcpy(chain_hdr, apdu + 1, 3);
            return respond(resp, NULL, 0, 0, SW_OK);
        }
        chaining = 0;
        data = cmd_buf;
        lc = cmd_len;
    }

    r = dispatch(ins, p1, p2, data, lc);
    if (data == cmd_buf)
        wipe(cmd_buf, cmd_len);
    return respond(resp, r.data, r.len, le, r.sw);
}

int piv_is_slow(const uint8_t *apdu, size_t len)
{
    if (len < 4)
        return 0;
    switch (apdu[1]) {
    case 0x87: case 0xdb: case 0xfe: case 0xff: case 0xfb: case 0x24: case 0x2c:
        return 1;
    }
    return 0;
}

void piv_reset(void)
{
    wipe(&sess, sizeof(sess));
    chaining = 0;
    pending_len = 0;
}

void piv_init(void)
{
    store_init();
    piv_reset();
}
